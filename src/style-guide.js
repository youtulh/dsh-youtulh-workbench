/** 口播文案的结构，也是他自己讲的：场景提问 → 破旧认知 → 立新说法 → 三条动作 → 再强调一次。 */
export const SCRIPT_STRUCTURE = `口播结构（他讲爆款拆解时自己总结的结构，按这个顺序写）：
1. 开头用具体场景提问，把人圈住：「我不知道咱们家里边有没有这样的孩子：……」
2. 接住情绪：先说家长现在有多着急、多难受，让他觉得你跟他站一边 —— 共情必须在方法前面，情绪没抚平，后面讲什么他都听不进去
3. 破掉旧认知：「不是孩子不努力，也不是天赋问题」
4. 立一个能听懂的说法，配一个具体场景解释它，讲到小白能懂
5. 讲 why：为什么是这样、为什么会变成这样，这一段要占一半以上；最后只给一半的 how —— 说清该做什么，但别把完整步骤给完，留一个钩子（具体怎么补、补多久，让他来找你）
6. 把结论再说一遍，落到一个动作（私信「诊断」／加微信）

另外：开头场景之后 5 秒内要给一句结论式判断，别让人听半天不知道你要说什么。`

