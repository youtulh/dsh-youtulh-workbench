// 牟老师的说话方式：规则和样本都从他自己 13 万字的课程稿里抽出来的。
// 用途：所有生成（选题、口播、私信话术）都要照这个来，不然一眼 AI。
// 抽样统计：平均句长 24 字（中位 20），「你」出现 2600 次、「我」2500 次，
// 而「首先/其次/总之/综上所述」加起来不到 25 次，「赋能/闭环/底层逻辑」几乎没有。

export const STYLE_RULES = `说话方式（照这个来，做不到就是 AI 味）：
- 用「你」直接对着家长说，别写「家长们」「各位家长」这种第三人称
- 一句一个意思，平均 20 到 25 字，长句拆开；说的时候要能一口气念完
- 多用口语连接词：其实、所以、但是、那、你看、就是说
- 讲机制，不讲形容词：不说「效果显著」，说「90% 的题都是从典型例题变出来的」
- 先破掉家长的旧认知，再立一个能听懂的说法，最后给能落地的动作
- 每段都带一个具体场景：几分、哪一章、哪类孩子
- 不用书面连接词：首先、其次、再次、总之、综上所述、值得注意的是
- 不用互联网黑话：赋能、闭环、底层逻辑、抓手、颗粒度
- 不喊口号、不堆排比、不用感叹号堆情绪；标题里不用「干货」「秘籍」「必看」`

/** 他自己的原话（短摘录），给模型当口气参考。 */
export const STYLE_SAMPLES = [
  '我不知道咱们家里边有没有这样的初中孩子：其他科目成绩都还可以，就数学感觉怎么补课、怎么刷题，成绩都提升不起来。这类孩子的问题该怎么解决？',
  '为什么我要反复给家长强调这一点？因为很多孩子数学学得不好，他老是会去找借口，认为自己没有学习天赋，结果导致孩子对数学的负面看法特别重。',
  '像这类孩子，我的建议是一定要学会去做三个事情。',
  '简单地说，就是孩子只要看到任何一条数学结论，我们全部试着理解，在理解的基础上把它们记下来。',
  '这个时候我们再去练习难题，去争取一个高分，而这个才是行之有效的、孩子能够操作的学数学的办法。',
]

/** 他常用的开头句式（从稿子里抽的），写口播时照着这种感觉起头。 */
export const HOOK_SAMPLES = [
  '我不知道咱们家里边有没有这样的孩子：其他科目成绩都还可以，就化学怎么补课、怎么刷题，成绩都提不起来。',
  '很多家长来找我的时候，他甚至不说自己孩子多大，你知道吗。',
  '你看人家这个孩子就确定得很明白：上次期末化学 85，这次 95。',
]

/** 口播文案的结构，也是他自己讲的：场景提问 → 破旧认知 → 立新说法 → 三条动作 → 再强调一次。 */
export const SCRIPT_STRUCTURE = `口播结构（他讲爆款拆解时自己总结的五段）：
1. 开头用具体场景提问，把人圈住：「我不知道咱们家里边有没有这样的孩子：……」
2. 先破掉家长的旧认知：「不是孩子不努力，也不是天赋问题」
3. 立一个能听懂的说法，配一个具体场景解释它
4. 给三条能直接做的动作，每条都要具体到「做什么、做多久、怎么算做到了」
5. 结尾把结论再说一遍，落到一个动作（私信「诊断」／加微信）`

export function styleMarkdown() {
  return `# 说话样本

> 这个文件是给助手看的口气参考。想让他更像你说话，可以把下面换成你自己的原话。
> 规则和样本都来自牟老师的课程文字稿。

## 规则

${STYLE_RULES.split('\n').slice(1).join('\n')}

## 口播结构

${SCRIPT_STRUCTURE.split('\n').slice(1).join('\n')}

## 原话样本

${STYLE_SAMPLES.map(row => `- ${row}`).join('\n')}
`
}

/** 拼进 prompt 的完整风格块。 */
export function styleBlock() {
  return `\n${STYLE_RULES}\n\n${SCRIPT_STRUCTURE}\n\n他本人说过的原话（口气参考，不要照抄内容）：\n${STYLE_SAMPLES.map(row => `- ${row}`).join('\n')}\n\n他常用的开头句式（换成你的科目，别照抄）：\n${HOOK_SAMPLES.map(row => `- ${row}`).join('\n')}\n`
}
